class wall_Manager {
  static update_Wall_States(Wall) {
    let above, north, south, east, west;
    try { above = Wall.above(1); } catch { }
    try { north = Wall.north(1); } catch { }
    try { south = Wall.south(1); } catch { }
    try { east = Wall.east(1); } catch { }
    try { west = Wall.west(1); } catch { }
    const blocks = [
      { block: above, side: "up" },
      { block: north, side: "north" },
      { block: south, side: "south" },
      { block: east, side: "east" },
      { block: west, side: "west" },
    ];
    for (const blockData of blocks) {
      const isSolid = isSolidBlock(blockData.block);
      if (blockData.side != "up") {
        Wall.setPermutation(Wall.permutation.withState("ntk:wall_connect_" + blockData.side, isSolid));
      }
      else {
        Wall.setPermutation(Wall.permutation.withState("ntk:wall_top_bit", isSolid));
      }
    }
    const north_state = Wall.permutation.getState("ntk:wall_connect_north");
    const south_state = Wall.permutation.getState("ntk:wall_connect_south");
    const east_state = Wall.permutation.getState("ntk:wall_connect_east");
    const west_state = Wall.permutation.getState("ntk:wall_connect_west");
    if ((north_state && south_state && !east_state && !west_state) || (!north_state && !south_state && east_state && west_state)) {
      Wall.setPermutation(Wall.permutation.withState("ntk:wall_slim", true));
      if (north_state && south_state) {
        Wall.setPermutation(Wall.permutation.withState("ntk:wall_slim_bit", "north_south"));
      }
      else {
        Wall.setPermutation(Wall.permutation.withState("ntk:wall_slim_bit", "east_west"));
      }
    }
    else {
      Wall.setPermutation(Wall.permutation.withState("ntk:wall_slim", false));
    }
  }
  static updateWallsAround(Block) {
    let above, below, north, south, east, west;
    try { above = Block.above(1); } catch { }
    try { below = Block.below(1); } catch { }
    try { north = Block.north(1); } catch { }
    try { south = Block.south(1); } catch { }
    try { east = Block.east(1); } catch { }
    try { west = Block.west(1); } catch { }
    const blocks = [Block, above, below, north, south, east, west];
    for (const block of blocks) {
      if (block != undefined && block.hasTag(wallTag)) {
        this.update_Wall_States(block);
      }
    }
  }
}

world.afterEvents.playerBreakBlock.subscribe((data) => {
  wall_Manager.updateWallsAround(data.block)
});

world.afterEvents.playerPlaceBlock.subscribe((data) => {
  wall_Manager.updateWallsAround(data.block)
});
